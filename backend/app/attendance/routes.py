"""Attendance routers (design §3, §7, §2B).

Every route is gated by ``require_permission(module, action)`` from Phase 0.
CRUD shape is generated by ``_make_crud_router`` (mirrors app/employee/routes.py);
DTR creation/update use dedicated handlers that run the calc core and set the
server-authoritative actor. DTR adjustments add an approval state machine.
"""


@owners_router.get(
    "/{obj_id}/lot",
    response_model=s.CategoryPublic,
    dependencies=[Depends(require_permission("owner", "view"))],
)
def read_owner_lot_via_category(session: SessionDep, obj_id) -> Any:
    """Point 3: resolve the Lot an Owner holds THROUGH the Category record.

    ``Owner`` has no FK to Lots; the authoritative link is
    Owner <- Category.owner_id, Category.lot_id -> Lots.
    """
    owner = get_active_by_id(session=session, model=m.Owner, obj_id=obj_id)
    if owner is None:
        raise HTTPException(status_code=404, detail="Owner not found")
    categories, _ = get_list(
        session=session, model=m.Category,
        filter_column=m.Category.owner_id, filter_value=owner.id, limit=1,
    )
    if not categories:
        raise HTTPException(status_code=404, detail="Owner has no Category record")
    return s.CategoryPublic.model_validate(categories[0])



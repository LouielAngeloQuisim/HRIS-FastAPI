def _employee_or_404(session: SessionDep, employee_id) -> m.EmployeeRecords:
    emp = get_active_by_id(session=session, model=m.EmployeeRecords, obj_id=employee_id)
    if emp is None:
        raise HTTPException(status_code=404, detail="Employee not found")
    return emp


def _ensure_annex_access(
    session: SessionDep,
    current_user: CurrentUser,
    employee: m.EmployeeRecords,
    *,
    elevated_action: PermissionAction = PermissionAction.EDIT,
) -> None:
    """Ownership check for 201-file annex/attachments.

    A user may access their OWN record (EmployeeRecords.user_id == caller). A
    non-owner must hold an elevated ``emp_list`` permission for the action.
    """
    if employee.user_id == current_user.id:
        return
    if user_has_permission(
        session=session, user=current_user, module_code="emp_list", action=elevated_action
    ):
        return
    raise HTTPException(
        status_code=403, detail="Not enough permissions to access this employee's records"
    )


def _make_crud_router(
    *,
    prefix: str,
    tag: str,
    module: str,
    model: Type,
    create: Type,
    update: Type,
    public: Type,
    listing: Type,
    custom_delete: bool = False,
) -> APIRouter:
    router = APIRouter(prefix=prefix, tags=[tag])
    model_name = model.__name__

    @router.get(
        "/",
        response_model=listing,
        dependencies=[Depends(require_permission(module, "view"))],
    )
    def list_objs(session: SessionDep, skip: int = 0, limit: int = 100) -> Any:
        rows, count = get_list(session=session, model=model, skip=skip, limit=limit)
        return listing(data=[public.model_validate(r) for r in rows], count=count)

    @router.get(
        "/{obj_id}",
        response_model=public,
        dependencies=[Depends(require_permission(module, "view"))],
    )
    def read_obj(session: SessionDep, obj_id) -> Any:
        db_obj = get_active_by_id(session=session, model=model, obj_id=obj_id)
        if db_obj is None:
            raise HTTPException(status_code=404, detail=f"{model_name} not found")
        return public.model_validate(db_obj)

    @router.post(
        "/",
        response_model=public,
        status_code=201,
        dependencies=[Depends(require_permission(module, "add"))],
    )
    def create_route(*, session: SessionDep, obj_in: create) -> Any:
        db_obj = create_obj(session=session, model=model, data=obj_in)
        return public.model_validate(db_obj)

    @router.patch(
        "/{obj_id}",
        response_model=public,
        dependencies=[Depends(require_permission(module, "edit"))],
    )
    def update_route(*, session: SessionDep, obj_id, obj_in: update) -> Any:
        db_obj = get_active_by_id(session=session, model=model, obj_id=obj_id)
        if db_obj is None:
            raise HTTPException(status_code=404, detail=f"{model_name} not found")
        return public.model_validate(update_obj(session=session, db_obj=db_obj, data=obj_in))

    if not custom_delete:
        @router.delete(
            "/{obj_id}",
            response_model=Message,
            dependencies=[Depends(require_permission(module, "delete"))],
        )
        def delete_route(session: SessionDep, obj_id) -> Any:
            db_obj = get_active_by_id(session=session, model=model, obj_id=obj_id)
            if db_obj is None:
                raise HTTPException(status_code=404, detail=f"{model_name} not found")
            soft_delete_obj(session=session, db_obj=db_obj)
            return Message(message=f"{model_name} deleted successfully")

    return router



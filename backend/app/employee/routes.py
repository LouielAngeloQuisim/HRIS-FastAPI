def delete_block(session: SessionDep, obj_id) -> Any:
    """Q7: 409 if an ACTIVE Category still references the Block."""
    db_obj = get_active_by_id(session=session, model=m.Blocks, obj_id=obj_id)
    if db_obj is None:
        raise HTTPException(status_code=404, detail="Block not found")
    if not ensure_not_referenced_by_active_category(session=session, blocks_id=db_obj.id):
        raise HTTPException(status_code=409, detail="Block is referenced by an active Category")
    soft_delete_obj(session=session, db_obj=db_obj)
    return Message(message="Block deleted successfully")



@divisions_router.delete(
    "/{obj_id}",
    response_model=Message,
    dependencies=[Depends(require_permission("division", "delete"))],
)
def delete_division(session: SessionDep, obj_id) -> Any:
    """Q4: block deletion if active Departments reference the Division (409)."""
    db_obj = get_active_by_id(session=session, model=m.Division, obj_id=obj_id)
    if db_obj is None:
        raise HTTPException(status_code=404, detail="Division not found")
    active_departments = get_list(
        session=session, model=m.Department, filter_column=m.Department.division_id,
        filter_value=db_obj.id, limit=1,
    )[1]
    if active_departments > 0:
        raise HTTPException(
            status_code=409,
            detail="Division has active departments; cannot delete",
        )
    soft_delete_obj(session=session, db_obj=db_obj)
    return Message(message="Division deleted successfully")



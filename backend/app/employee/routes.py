@employees_router.get(
    "/me",
    response_model=s.EmployeeRecordsPublic,
    dependencies=[Depends(require_permission("emp_list", "view"))],
)
def read_own_employee(session: SessionDep, current_user: CurrentUser) -> Any:
    """Self-service read of the caller's own employee record (ownership check)."""
    db_obj = get_list(
        session=session, model=m.EmployeeRecords,
        filter_column=m.EmployeeRecords.user_id, filter_value=current_user.id, limit=1,
    )[0]
    if not db_obj:
        raise HTTPException(status_code=404, detail="No employee record for this user")
    return s.EmployeeRecordsPublic.model_validate(db_obj[0])


@employees_router.get(
    "/{employee_id}/additional-records",
    response_model=s.EmployeeAdditionalRecordsPublic,
)
def read_additional_records(
    session: SessionDep, employee_id, current_user: CurrentUser
) -> Any:
    """Read a single employee's 201-file annex (ownership-checked)."""
    employee = _employee_or_404(session, employee_id)
    _ensure_annex_access(session, current_user, employee, elevated_action=PermissionAction.VIEW)
    annex = get_additional_records_for_employee(session=session, employee_id=employee.id)
    if annex is None:
        raise HTTPException(status_code=404, detail="Additional records not found")
    return s.EmployeeAdditionalRecordsPublic.model_validate(annex)


@employees_router.patch(
    "/{employee_id}/additional-records",
    response_model=s.EmployeeAdditionalRecordsPublic,
)
def update_additional_records(
    *, session: SessionDep, employee_id, body: s.EmployeeAdditionalRecordsUpdate,
    current_user: CurrentUser,
) -> Any:
    """Upsert a single employee's 201-file annex (ownership-checked)."""
    employee = _employee_or_404(session, employee_id)
    _ensure_annex_access(session, current_user, employee, elevated_action=PermissionAction.EDIT)
    annex = upsert_additional_records(session=session, employee_id=employee.id, data=body)
    return s.EmployeeAdditionalRecordsPublic.model_validate(annex)


@employees_router.get(
    "/{employee_id}/attachments",
    response_model=s.EmployeeAttachmentsList,
)
def list_attachments(
    session: SessionDep, employee_id, current_user: CurrentUser
) -> Any:
    """List an employee's uploaded documents (ownership-checked)."""
    employee = _employee_or_404(session, employee_id)
    _ensure_annex_access(session, current_user, employee, elevated_action=PermissionAction.VIEW)
    rows, count = get_attachments_for_employee(session=session, employee_id=employee.id)
    return s.EmployeeAttachmentsList(
        data=[s.EmployeeAttachmentsPublic.model_validate(r) for r in rows], count=count
    )


@employees_router.post(
    "/{employee_id}/attachments",
    response_model=s.EmployeeAttachmentsPublic,
    status_code=201,
)
def upload_attachment(
    *,
    session: SessionDep,
    employee_id,
    current_user: CurrentUser,
    file: UploadFile = File(...),
    type: str | None = Form(default=None),
    attachment_name: str | None = Form(default=None),
) -> Any:
    """Upload a document; the file is stored outside the web root, only its
    path is persisted on the DB row."""
    employee = _employee_or_404(session, employee_id)
    _ensure_annex_access(session, current_user, employee, elevated_action=PermissionAction.ADD)
    content = file.file.read()
    stored_path = store_attachment_file(
        employee_id=employee.id, filename=file.filename or "", content=content
    )
    db_obj = create_attachment(
        session=session,
        employee_id=employee.id,
        data=s.EmployeeAttachmentsCreate(
            type=type, attachment_name=attachment_name, original_file_name=file.filename
        ),
        file_path=stored_path,
        attachment_size=len(content),
    )
    return s.EmployeeAttachmentsPublic.model_validate(db_obj)


@employees_router.delete(
    "/{employee_id}/attachments/{attachment_id}",
    response_model=Message,
)
def delete_attachment(
    session: SessionDep, employee_id, attachment_id, current_user: CurrentUser
) -> Any:
    employee = _employee_or_404(session, employee_id)
    _ensure_annex_access(
        session, current_user, employee, elevated_action=PermissionAction.DELETE
    )
    attachment = get_attachment_by_id(session=session, attachment_id=attachment_id)
    if attachment is None or attachment.employee_id != employee.id:
        raise HTTPException(status_code=404, detail="Attachment not found")
    soft_delete_attachment(session=session, db_obj=attachment)
    return Message(message="Attachment deleted successfully")


